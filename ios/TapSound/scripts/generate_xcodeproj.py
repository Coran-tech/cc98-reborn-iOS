    (scheme_dir / f"{APP_NAME}.xcscheme").write_text(SCHEME, encoding="utf-8", newline="\n")
    workspace_dir = PROJECT_DIR / "project.xcworkspace"
    workspace_dir.mkdir(parents=True, exist_ok=True)
